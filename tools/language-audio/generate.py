#!/usr/bin/env python3
"""
Records every line the language courses speak with native neural voices
(Microsoft Edge "Neural" voices, via the edge-tts package) into assets/audio/lang/,
and writes assets/audio/lang/clips.js, the list of recordings the site plays.

    pip install edge-tts
    python3 tools/language-audio/generate.py            # record what is missing
    python3 tools/language-audio/generate.py --prune    # also delete recordings no longer used
    python3 tools/language-audio/generate.py --redo     # record everything again

Run it again after editing assets/js/language-data.js or the VOICES cast in
assets/js/language-voice.js. Needs Node.js (to read the course data) and internet access.
"""
import argparse, asyncio, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "audio", "lang")


def lines():
    js = os.path.join(ROOT, "tools", "language-audio", "list.js")
    return json.loads(subprocess.check_output(["node", js], cwd=ROOT))


async def record(item, sem):
    import edge_tts
    dest = os.path.join(OUT, item["key"] + ".mp3")
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(item["text"], item["voice"]).save(dest + ".part")
                os.replace(dest + ".part", dest)
                print("  ok ", item["key"], item["voice"], item["text"][:50])
                return True
            except Exception as e:  # network hiccup: try again
                if attempt == 3:
                    print("  FAIL", item["key"], item["voice"], item["text"][:50], "-", e, file=sys.stderr)
                await asyncio.sleep(2 * (attempt + 1))
    return False


def write_manifest():
    keys = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith(".mp3"))
    with open(os.path.join(OUT, "clips.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/language-audio/generate.py: the native-voice recordings that exist. */\n")
        f.write("window.AZ_AUDIO_CLIPS = {" + ",".join('"%s":1' % k for k in keys) + "};\n")
    return len(keys)


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prune", action="store_true", help="delete recordings no longer used")
    ap.add_argument("--redo", action="store_true", help="record every line again")
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    items = lines()
    want = {i["key"] for i in items}
    todo = [i for i in items if a.redo or not os.path.exists(os.path.join(OUT, i["key"] + ".mp3"))]
    print(f"{len(items)} lines, {len(todo)} to record")
    sem = asyncio.Semaphore(4)
    results = await asyncio.gather(*(record(i, sem) for i in todo))
    if a.prune:
        for f in os.listdir(OUT):
            if f.endswith(".mp3") and f[:-4] not in want:
                os.remove(os.path.join(OUT, f))
                print("  removed", f)
    n = write_manifest()
    print(f"{n} recordings listed in clips.js; {results.count(False)} failed")


if __name__ == "__main__":
    asyncio.run(main())
