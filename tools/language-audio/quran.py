#!/usr/bin/env python3
"""
Downloads real Qur'an recitation for every course line or word that has a `q` reference
(see the notes at the top of assets/js/language-data.js) into assets/audio/quran/,
and writes assets/audio/quran/clips.js, the list of recitations the site plays.

    python3 tools/language-audio/quran.py           # fetch what is missing
    python3 tools/language-audio/quran.py --redo    # fetch everything again

  "s:a"        whole verse, Mishary Alafasy (verses.quran.com)
  "s:a:w1-w2"  words w1..w2 cut from Alafasy's verse audio, using Quran.com's word timings
  "s:a:w"      one word from Quran.com's word-by-word recitation (audio.qurancdn.com)

Needs Node.js, ffmpeg and internet access.
"""
import argparse, json, os, shutil, subprocess, sys, tempfile, urllib.request

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "audio", "quran")
API = "https://api.quran.com/api/v4"
ALAFASY = 7  # Quran.com recitation id for Mishary Rashid Alafasy (has word timings)
PAD_MS = 60  # breathing room either side of a cut


def refs():
    js = r"""
    const fs=require("fs"),vm=require("vm");const c={window:{}};c.globalThis=c.window;vm.createContext(c);
    vm.runInContext(fs.readFileSync("assets/js/language-data.js","utf8").replace(/\bwindow\./g,"globalThis."),c);
    const W=c.window,all=W.AZ_COURSES.concat([W.AZ_COURSE_ENGLISH]),out=new Set();
    for(const C of all){(C.scenes||[]).forEach(s=>s.lines.forEach(l=>l.q&&out.add(l.q)));
      C.lessons.forEach(l=>l.words.forEach(w=>w.q&&out.add(w.q)));}
    console.log(JSON.stringify([...out]));"""
    return json.loads(subprocess.check_output(["node", "-e", js], cwd=ROOT))


def name(ref):
    return ref.replace(":", "_")


def get(url):
    req = urllib.request.Request(url, headers={"User-Agent": "language-course-audio"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def ffmpeg(*args):
    subprocess.run(["ffmpeg", "-v", "error", "-y", *args], check=True)


def fetch(ref, dest):
    parts = ref.split(":")
    s, a = int(parts[0]), int(parts[1])
    tmp = tempfile.mkdtemp()
    try:
        if len(parts) == 3 and "-" not in parts[2]:
            # a single word, recited on its own
            w = int(parts[2])
            open(dest, "wb").write(get("https://audio.qurancdn.com/wbw/%03d_%03d_%03d.mp3" % (s, a, w)))
            return
        info = json.loads(get("%s/recitations/%d/by_ayah/%d:%d?fields=segments" % (API, ALAFASY, s, a)))["audio_files"][0]
        src = os.path.join(tmp, "verse.mp3")
        open(src, "wb").write(get("https://verses.quran.com/" + info["url"]))
        if len(parts) == 2:
            ffmpeg("-i", src, "-c:a", "libmp3lame", "-b:a", "96k", dest)
            return
        w1, w2 = (int(x) for x in parts[2].split("-"))
        segs = {sg[1]: (sg[2], sg[3]) for sg in info["segments"] if len(sg) >= 4}
        if w1 not in segs or w2 not in segs:
            raise ValueError("no word timings for words %d-%d" % (w1, w2))
        start = max(0, segs[w1][0] - PAD_MS) / 1000
        end = (segs[w2][1] + PAD_MS) / 1000
        ffmpeg("-ss", "%.3f" % start, "-to", "%.3f" % end, "-i", src,
               "-af", "afade=t=in:d=0.04,areverse,afade=t=in:d=0.08,areverse",
               "-c:a", "libmp3lame", "-b:a", "96k", dest)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--redo", action="store_true")
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    rs = refs()
    failed = 0
    for ref in rs:
        dest = os.path.join(OUT, name(ref) + ".mp3")
        if os.path.exists(dest) and not a.redo:
            continue
        try:
            fetch(ref, dest + ".part.mp3")
            os.replace(dest + ".part.mp3", dest)
            print("  ok ", ref)
        except Exception as e:
            failed += 1
            print("  FAIL", ref, "-", e, file=sys.stderr)
            if os.path.exists(dest + ".part.mp3"):
                os.remove(dest + ".part.mp3")
    have = sorted(r for r in rs if os.path.exists(os.path.join(OUT, name(r) + ".mp3")))
    with open(os.path.join(OUT, "clips.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/language-audio/quran.py: Qur'an recitations the language courses play. */\n")
        f.write("window.AZ_QURAN_CLIPS = {" + ",".join('"%s":1' % r for r in have) + "};\n")
    print("%d recitations listed in clips.js; %d failed" % (len(have), failed))


if __name__ == "__main__":
    main()
