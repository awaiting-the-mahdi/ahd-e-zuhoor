#!/usr/bin/env python3
"""
Records the Knowledge Library's chapter summaries as narration (English: Christopher;
Urdu: Asad; Microsoft neural voices via edge-tts), into assets/audio/library/<lang>/<hash>.mp3,
and writes assets/audio/library/clips.js, which tells the reader which clips exist.

    pip install edge-tts
    python3 tools/library-audio/make.py            # record what is new or changed
    python3 tools/library-audio/make.py --prune    # also delete clips no longer used

A clip's file name is a hash of its text, so editing a summary re-records only that chapter.
Behind an HTTPS proxy set SSL_CERT_FILE to the proxy's CA bundle. Needs Node.js.
"""
import argparse, asyncio, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "audio", "library")
VOICE = {"en": "en-US-ChristopherNeural", "ur": "ur-PK-AsadNeural"}
STYLE = {"rate": "-10%", "pitch": "-4Hz"}   # slower and a little deeper: a documentary narrator
PROXY = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy") or None
if os.environ.get("SSL_CERT_FILE"):
    import certifi
    certifi.where = lambda: os.environ["SSL_CERT_FILE"]


def chapters():
    js = os.path.join(ROOT, "tools", "library-audio", "list.js")
    return json.loads(subprocess.check_output(["node", js], cwd=ROOT))


async def record(c, sem):
    import edge_tts
    dest = os.path.join(OUT, c["lang"], c["hash"] + ".mp3")
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(c["text"], VOICE[c["lang"]], proxy=PROXY, **STYLE).save(dest + ".part")
                os.replace(dest + ".part", dest)
                print("  ok ", c["lang"], c["key"], c["title"][:50], flush=True)
                return True
            except Exception as e:
                if os.path.exists(dest + ".part"):
                    os.remove(dest + ".part")
                if attempt == 3:
                    print("  FAIL", c["lang"], c["key"], e, file=sys.stderr, flush=True)
                await asyncio.sleep(3 * (attempt + 1))
    return False


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prune", action="store_true")
    a = ap.parse_args()
    cs = chapters()
    for lang in VOICE:
        os.makedirs(os.path.join(OUT, lang), exist_ok=True)
    todo = [c for c in cs if not os.path.exists(os.path.join(OUT, c["lang"], c["hash"] + ".mp3"))]
    print(f"{len(cs)} chapters, {len(todo)} to record", flush=True)
    sem = asyncio.Semaphore(3)
    res = await asyncio.gather(*(record(c, sem) for c in todo))
    if a.prune:
        want = {(c["lang"], c["hash"]) for c in cs}
        for lang in VOICE:
            for f in os.listdir(os.path.join(OUT, lang)):
                if f.endswith(".mp3") and (lang, f[:-4]) not in want:
                    os.remove(os.path.join(OUT, lang, f)); print("  removed", lang, f)
    # clips.js: AZ_LIB_AUDIO.en["book-chapter"] = "hash" (only clips that exist)
    m = {lang: {} for lang in VOICE}
    for c in cs:
        if os.path.exists(os.path.join(OUT, c["lang"], c["hash"] + ".mp3")):
            m[c["lang"]][c["key"]] = c["hash"]
    with open(os.path.join(OUT, "clips.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/library-audio/make.py: the recorded chapter narrations. */\n")
        f.write("window.AZ_LIB_AUDIO = " + json.dumps(m, separators=(",", ":")) + ";\n")
    print(f"clips: en {len(m['en'])}, ur {len(m['ur'])}; failed {res.count(False)}", flush=True)


if __name__ == "__main__":
    asyncio.run(main())
