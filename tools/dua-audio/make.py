#!/usr/bin/env python3
"""
Records the Arabic of every dua and hadith on the Duas & Hadiths page with a native Arabic
neural voice (Microsoft Edge "Neural" voices, via edge-tts) into assets/audio/duas/, and
writes assets/audio/duas/clips.js, the list the page plays from.

    pip install edge-tts
    python3 tools/dua-audio/make.py           # record what is missing
    python3 tools/dua-audio/make.py --prune   # also delete recordings no longer used

Run it again after editing assets/js/duas-data.js or assets/js/marefat-data.js.
Needs Node.js and internet access.
"""
import argparse, asyncio, json, os, subprocess, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "assets", "audio", "duas")
VOICE, RATE, PITCH = "ar-IQ-BasselNeural", "-10%", "-2Hz"   # an Iraqi voice, calm and clear (after changing it, run with --redo)

PROXY = os.environ.get("HTTPS_PROXY") or os.environ.get("https_proxy") or None
if os.environ.get("SSL_CERT_FILE"):
    import certifi
    certifi.where = lambda: os.environ["SSL_CERT_FILE"]


async def record(item, sem):
    import edge_tts
    dest = os.path.join(OUT, item["key"] + ".mp3")
    async with sem:
        for attempt in range(4):
            try:
                await edge_tts.Communicate(item["text"], VOICE, rate=RATE, pitch=PITCH, proxy=PROXY).save(dest + ".part")
                os.replace(dest + ".part", dest)
                print("  ok ", item["key"], item["where"])
                return True
            except Exception as e:
                if attempt == 3:
                    print("  FAIL", item["key"], item["where"], "-", e, file=sys.stderr)
                await asyncio.sleep(2 * (attempt + 1))
    return False


async def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--prune", action="store_true")
    ap.add_argument("--redo", action="store_true")
    a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    items = json.loads(subprocess.check_output(["node", os.path.join(ROOT, "tools", "dua-audio", "list.js")], cwd=ROOT))
    todo = [i for i in items if a.redo or not os.path.exists(os.path.join(OUT, i["key"] + ".mp3"))]
    print(f"{len(items)} passages, {len(todo)} to record")
    sem = asyncio.Semaphore(4)
    res = await asyncio.gather(*(record(i, sem) for i in todo)) if todo else []
    if a.prune:
        want = {i["key"] for i in items}
        for f in os.listdir(OUT):
            if f.endswith(".mp3") and f[:-4] not in want:
                os.remove(os.path.join(OUT, f)); print("  removed", f)
    keys = sorted(f[:-4] for f in os.listdir(OUT) if f.endswith(".mp3"))
    with open(os.path.join(OUT, "clips.js"), "w", encoding="utf-8") as f:
        f.write("/* Generated by tools/dua-audio/make.py: the Arabic recordings of the duas and hadiths. */\n")
        f.write("window.AZ_DUA_CLIPS = {" + ",".join('"%s":1' % k for k in keys) + "};\n")
    print(f"{len(keys)} recordings; {res.count(False)} failed")

asyncio.run(main())
